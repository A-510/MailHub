    def clear_demo_data(self, db: Session) -> int:
        """清除所有标记为 is_demo=True 的演示邮箱及其关联邮件，返回删除账号数。"""
        demo_accounts = list(db.scalars(select(Account).where(Account.is_demo.is_(True))).all())
        count = len(demo_accounts)
        for acc in demo_accounts:
            db.delete(acc)
        db.commit()
        logger.info("Cleared %d demo accounts.", count)
        return count


